package dev.gpucodeforces.judge.executor.processor.coralnpu

import dev.gpucodeforces.judge.api.CSignature
import dev.gpucodeforces.judge.api.ParamRole
import dev.gpucodeforces.judge.api.ParamSpec
import dev.gpucodeforces.judge.api.Signature
import org.intellij.lang.annotations.Language

/**
 * What the judge links with the contestant's `solve` on `coral-npu`: the first instructions the core runs
 * ([START]), the memory map ([LINKER_SCRIPT]) and a `judge_main` that calls `solve` ([generate]). There is no
 * operating system and no I/O: the judge, as the host of the core, writes the arrays of a test straight into the data
 * memory and the arguments into the words of `judge_args`, and reads the outputs back when the core halts.
 */
object CoralNpuHarness {
    /** Part of the build cache key. */
    const val VERSION = "1"

    /** The words of `judge_args` one parameter takes, from [first]. */
    data class ArgWords(val param: ParamSpec, val first: Int, val count: Int)

    /** An array is its address; a scalar its raw bits, the low word first. */
    fun argWords(sig: Signature): List<ArgWords> {
        var next = 0
        return sig.params.map { p ->
            val count = if (p.role == ParamRole.SCALAR && p.type.bytes > WORD_BYTES) 2 else 1
            ArgWords(p, next, count).also { next += count }
        }
    }

    /** `judge_main` for [sig]: valid C and C++, compiled by the compiler of the submission like `solve` itself. */
    fun generate(sig: Signature): String = buildString {
        val words = argWords(sig)
        append(PRELUDE)
        appendLine("${CSignature.declaration(sig)};")
        appendLine()
        appendLine("/* Filled by the judge before the core starts. */")
        appendLine("__attribute__((section(\".judge_args\"), used)) uint32_t judge_args[${words.sumOf { it.count }.coerceAtLeast(1)}];")
        appendLine()
        appendLine("#ifdef __cplusplus")
        appendLine("extern \"C\"")
        appendLine("#endif")
        appendLine("void judge_main(void) {")
        appendLine("    for (judge_init* init = __judge_init_start; init != __judge_init_end; init++) (*init)();")
        for (w in words.filter { it.param.role == ParamRole.SCALAR }) {
            appendLine("    ${CSignature.type(w.param.type)} ${w.param.name}_v; memcpy(&${w.param.name}_v, &judge_args[${w.first}], sizeof ${w.param.name}_v);")
        }
        val args = words.joinToString(", ") { w ->
            val p = w.param
            if (p.role == ParamRole.SCALAR) "${p.name}_v" else "(${CSignature.paramDecl(p).substringBeforeLast(p.name).trim()})judge_args[${w.first}]"
        }
        appendLine("    ${sig.function}($args);")
        appendLine("}")
    }

    private const val WORD_BYTES = 4

    @Language("C")
    private val PRELUDE = """
        // Generated by the judge (CoralNpuHarness), version $VERSION.
        #include <stdint.h>
        #include <string.h>

        typedef void (*judge_init)(void);
        extern judge_init __judge_init_start[], __judge_init_end[];


    """.trimIndent() + "\n"

    /**
     * The entry point. Bits 9-10 and 13-14 of `mstatus` turn the vector and the floating point state on; `mpause`
     * (a Coral NPU instruction, 0x08000073) halts the core, which is how the judge sees the program end.
     */
    val START = """
        // Generated by the judge (CoralNpuHarness), version $VERSION.
            .section .text.judge_start, "ax"
            .globl _start
        _start:
            .option push
            .option norelax
            la gp, __global_pointer${'$'}
            .option pop
            la sp, __judge_stack_top
            la tp, __judge_tls
            li t0, 0x6600
            csrs mstatus, t0
            call judge_main
            .word 0x08000073
        1:  j 1b
    """.trimIndent() + "\n"

    /**
     * Code goes to the instruction memory and everything else, constants included, to the data memory: the core
     * cannot read its instruction memory. `judge_args` is the first thing in the data memory, so the judge knows
     * its address; the stack grows down from the end of the data memory.
     */
    val LINKER_SCRIPT = """
        /* Generated by the judge (CoralNpuHarness), version $VERSION. */
        MEMORY {
            ITCM (rx) : ORIGIN = ${CoralNpuMemory.INSTRUCTION_START}, LENGTH = ${CoralNpuMemory.INSTRUCTION_BYTES}
            DTCM (rw) : ORIGIN = ${CoralNpuMemory.DATA_START}, LENGTH = ${CoralNpuMemory.DATA_BYTES}
        }
        ENTRY(_start)
        SECTIONS {
            .text : { KEEP(*(.text.judge_start)) *(.text .text.*) } > ITCM
            .judge_args : { KEEP(*(.judge_args)) } > DTCM
            .rodata : { *(.rodata .rodata.* .srodata .srodata.*) } > DTCM
            .init_array : {
                __judge_init_start = .;
                KEEP(*(.preinit_array)) KEEP(*(SORT_BY_INIT_PRIORITY(.init_array.*))) KEEP(*(.init_array))
                __judge_init_end = .;
            } > DTCM
            .data : { *(.data .data.*) __global_pointer${'$'} = . + 0x800; *(.sdata .sdata.*) } > DTCM
            . = ALIGN(16);
            __judge_tls = .;
            .tdata : ALIGN(16) { *(.tdata .tdata.*) } > DTCM
            .tbss (NOLOAD) : ALIGN(16) { *(.tbss .tbss.*) *(.tcommon) } > DTCM
            /* ld does not advance the location counter over .tbss: this makes room for it */
            .tbss_space (NOLOAD) : { . = ADDR(.tbss); . = . + SIZEOF(.tbss); } > DTCM
            .bss (NOLOAD) : { *(.sbss .sbss.*) *(.bss .bss.*) *(COMMON) } > DTCM
            __judge_stack_top = ORIGIN(DTCM) + LENGTH(DTCM);
            /DISCARD/ : { *(.eh_frame .eh_frame.*) *(.note.*) }
        }
    """.trimIndent() + "\n"
}
