package dev.gpucodeforces.judge.executor.processor.gpucuda

import dev.gpucodeforces.judge.api.CudaSignature
import dev.gpucodeforces.judge.api.DType
import dev.gpucodeforces.judge.api.MemorySpace
import dev.gpucodeforces.judge.api.ParamRole
import dev.gpucodeforces.judge.api.Signature

/**
 * Generates the harness `main` for a signature. The harness owns all data movement; the contestant's function is
 * called through [CudaSignature.declaration], so a signature mismatch is a link error.
 */
object HarnessGenerator {

    /** Runtime entry points wrapped at link time for GPU_KERNELS timing (always wrapped, see runtime.h). */
    val WRAPPED_SYMBOLS = listOf(
        "cudaLaunchKernel", "cudaLaunchKernel_ptsz",
        "cudaLaunchCooperativeKernel", "cudaLaunchCooperativeKernel_ptsz",
        "cudaLaunchKernelExC", "cudaLaunchKernelExC_ptsz",
    )

    fun generate(sig: Signature): String = buildString {
        appendLine("// Generated by the GPU Codeforces judge. Do not edit.")
        appendLine("#include \"judge/runtime.h\"")
        CudaSignature.typeIncludes(sig).forEach { appendLine("#include <$it>") }
        appendLine()
        appendLine("${CudaSignature.declaration(sig)};")
        appendLine()
        appendLine("static const judge::ParamDesc judge_params[] = {")
        for (p in sig.params) {
            val role = when (p.role) {
                ParamRole.INPUT -> "Input"
                ParamRole.OUTPUT -> "Output"
                ParamRole.INOUT -> "InOut"
                ParamRole.SCALAR -> "Scalar"
            }
            val mem = when (p.memory) {
                MemorySpace.DEVICE -> "Device"
                MemorySpace.HOST -> "Host"
                null -> "None"
            }
            val kind = if (p.role != ParamRole.SCALAR) "0" else "'${scalarKind(p.type)}'"
            appendLine("    {\"${p.name}\", ${p.type.bytes}, judge::Role::$role, judge::Mem::$mem, $kind},")
        }
        appendLine("};")
        appendLine()
        appendLine("static void judge_invoke(void* const* p, const judge::Scalar* s) {")
        val args = sig.params.mapIndexed { i, p ->
            when (p.role) {
                ParamRole.INPUT -> "static_cast<const ${p.type.cppType}*>(p[$i])"
                ParamRole.OUTPUT, ParamRole.INOUT -> "static_cast<${p.type.cppType}*>(p[$i])"
                ParamRole.SCALAR -> "static_cast<${p.type.cppType}>(s[$i].${scalarKind(p.type).let { if (it == 'f') 'd' else it }})"
            }
        }
        appendLine("    ${sig.function}(${args.joinToString(", ")});")
        appendLine("}")
        appendLine()
        appendLine("int main(int argc, char** argv) {")
        appendLine("    return judge::run_harness(argc, argv, judge_params, ${sig.params.size}, judge_invoke);")
        appendLine("}")
    }

    private fun scalarKind(t: DType): Char = when {
        t.floating -> 'f'
        t == DType.UINT32 || t == DType.UINT64 -> 'u'
        else -> 'i'
    }
}
