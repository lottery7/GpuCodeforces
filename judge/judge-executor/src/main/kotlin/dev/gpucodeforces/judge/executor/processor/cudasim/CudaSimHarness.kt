package dev.gpucodeforces.judge.executor.processor.cudasim

import dev.gpucodeforces.judge.api.CudaSignature
import dev.gpucodeforces.judge.api.ParamRole
import dev.gpucodeforces.judge.api.Signature
import org.intellij.lang.annotations.Language

/**
 * The judge's `main` on `cuda-sim`: not the harness of `gpu-cuda`, which times and repeats calls on a real GPU. This
 * one calls `solve` once: every array is device memory filled from the test (outputs with 0xFF bytes), and after a
 * synchronization the outputs are copied back to files.
 *
 * Arguments: a manifest (`scalar <name> <raw bits>`, `array <name> <elements> <input or -> <output or ->`, as on the
 * other emulated processors) and the run's nonce, printed as `<nonce> done` once the outputs are written. A CUDA
 * error is `<nonce> error <text>` and exit code [EXIT_ERROR]; a broken manifest exit code [EXIT_BROKEN].
 */
object CudaSimHarness {
    /** Part of the build cache key. */
    const val VERSION = "1"

    private const val TYPE_INCLUDES = "// type includes"

    const val EXIT_BROKEN = 2
    const val EXIT_ERROR = 3

    fun generate(sig: Signature): String = buildString {
        append(PRELUDE.replace(TYPE_INCLUDES, CudaSignature.typeIncludes(sig).joinToString("\n") { "#include <$it>" }))
        appendLine("${CudaSignature.declaration(sig)};")
        appendLine()
        appendLine("int main(int argc, char** argv) {")
        appendLine("    if (argc != 3) broken(\"usage: harness <manifest> <nonce>\");")
        appendLine("    nonce = argv[2];")
        for (p in sig.params) {
            if (p.role == ParamRole.SCALAR) appendLine("    ${p.type.cppType} ${p.name}_v; int ${p.name}_set = 0;")
            else appendLine("    Array ${p.name}_a = {}; int ${p.name}_set = 0;")
        }
        appendLine("    FILE* m = fopen(argv[1], \"r\");")
        appendLine("    if (!m) broken(\"cannot open the manifest\");")
        appendLine("    char kind[16], name[64], in[4096], out[4096];")
        appendLine("    unsigned long long value, elements;")
        appendLine("    while (fscanf(m, \"%15s %63s\", kind, name) == 2) {")
        appendLine("        if (!strcmp(kind, \"scalar\")) {")
        appendLine("            if (fscanf(m, \"%llu\", &value) != 1) broken(\"bad scalar\");")
        for (p in sig.scalars) appendLine("            if (!strcmp(name, \"${p.name}\")) { memcpy(&${p.name}_v, &value, sizeof ${p.name}_v); ${p.name}_set = 1; continue; }")
        appendLine("        } else if (!strcmp(kind, \"array\")) {")
        appendLine("            if (fscanf(m, \"%llu %4095s %4095s\", &elements, in, out) != 3) broken(\"bad array\");")
        for (p in sig.arrays) appendLine("            if (!strcmp(name, \"${p.name}\")) { ${p.name}_a = load(elements, ${p.type.bytes}, in, out); ${p.name}_set = 1; continue; }")
        appendLine("        }")
        appendLine("        broken(\"unknown manifest entry\");")
        appendLine("    }")
        appendLine("    fclose(m);")
        appendLine("    if (${sig.params.joinToString(" || ") { "!${it.name}_set" }}) broken(\"incomplete manifest\");")
        val args = sig.params.joinToString(", ") { p ->
            if (p.role == ParamRole.SCALAR) "${p.name}_v" else "(${CudaSignature.paramDecl(p).substringBeforeLast(p.name).trim()})${p.name}_a.device"
        }
        appendLine("    ${sig.function}($args);")
        appendLine("    check(cudaGetLastError(), \"solve\");")
        appendLine("    check(cudaDeviceSynchronize(), \"the kernels of solve\");")
        for (p in sig.outputs) appendLine("    save(&${p.name}_a);")
        appendLine("    printf(\"%s done\\n\", nonce);")
        appendLine("    fflush(stdout);")
        appendLine("    return 0;")
        appendLine("}")
    }

    @Language("CUDA")
    private val PRELUDE = """
        // Generated by the judge (CudaSimHarness), version $VERSION.
        #include <cstdint>
        #include <cstdio>
        #include <cstdlib>
        #include <cstring>
        #include <vector>
        #include <cuda_runtime.h>
        $TYPE_INCLUDES

        struct Array {
            void* device;
            size_t bytes;
            char out[4096];
        };

        static const char* nonce = "";

        static void broken(const char* what) {
            fprintf(stderr, "harness: %s\n", what);
            exit($EXIT_BROKEN);
        }

        static void check(cudaError_t e, const char* what) {
            if (e == cudaSuccess) return;
            printf("%s error %s: %s\n", nonce, what, cudaGetErrorString(e));
            fflush(stdout);
            exit($EXIT_ERROR);
        }

        static Array load(unsigned long long elements, size_t size, const char* in, const char* out) {
            Array a = {};
            a.bytes = (size_t)elements * size;
            snprintf(a.out, sizeof a.out, "%s", strcmp(out, "-") ? out : "");
            check(cudaMalloc(&a.device, a.bytes ? a.bytes : 1), "cudaMalloc");
            check(cudaMemset(a.device, 0xFF, a.bytes), "cudaMemset");
            if (strcmp(in, "-")) {
                std::vector<unsigned char> host(a.bytes);
                FILE* f = fopen(in, "rb");
                if (!f || fread(host.data(), 1, a.bytes, f) != a.bytes) broken("cannot read an input");
                fclose(f);
                check(cudaMemcpy(a.device, host.data(), a.bytes, cudaMemcpyHostToDevice), "copying an input");
            }
            return a;
        }

        static void save(const Array* a) {
            std::vector<unsigned char> host(a->bytes);
            check(cudaMemcpy(host.data(), a->device, a->bytes, cudaMemcpyDeviceToHost), "copying an output");
            FILE* f = fopen(a->out, "wb");
            if (!f || fwrite(host.data(), 1, a->bytes, f) != a->bytes || fclose(f)) broken("cannot write an output");
        }


    """.trimIndent() + "\n"
}
