package dev.gpucodeforces.judge.executor.processor.riscv

import dev.gpucodeforces.judge.api.CSignature
import dev.gpucodeforces.judge.api.ParamRole
import dev.gpucodeforces.judge.api.Signature
import org.intellij.lang.annotations.Language

/**
 * The judge's `main` on `riscv-rvv`, linked statically with the contestant's `solve`. It is valid C and C++: it is
 * compiled by the compiler of the submission, so a C++ `solve` keeps C++ linkage and a C or assembly one C linkage.
 *
 * The only argument is a manifest with lines `scalar <name> <raw bits>` and
 * `array <name> <elements> <input file or -> <output file or ->`, as on `rtl`. Arrays are 64-byte aligned host memory;
 * outputs start as 0xFF bytes. The harness prints nothing: stdout belongs to the judge's QEMU plugin. A broken
 * manifest or file is exit code [EXIT_BROKEN].
 */
object RiscvHarness {
    /** Part of the build cache key. */
    const val VERSION = "1"

    const val EXIT_BROKEN = 2

    fun generate(sig: Signature): String = buildString {
        append(PRELUDE)
        appendLine("${CSignature.declaration(sig)};")
        appendLine()
        appendLine("int main(int argc, char** argv) {")
        appendLine("    if (argc != 2) broken(\"usage: harness <manifest>\");")
        for (p in sig.params) {
            val type = CSignature.type(p.type)
            if (p.role == ParamRole.SCALAR) appendLine("    $type ${p.name}_v; int ${p.name}_set = 0;")
            else appendLine("    Array ${p.name}_a = {0, 0, \"\"}; int ${p.name}_set = 0;")
        }
        appendLine("    FILE* m = fopen(argv[1], \"r\");")
        appendLine("    if (!m) broken(\"cannot open the manifest\");")
        appendLine("    char kind[16], name[64], in[PATH_LEN], out[PATH_LEN];")
        appendLine("    unsigned long long value, elements;")
        appendLine("    while (fscanf(m, \"%15s %63s\", kind, name) == 2) {")
        appendLine("        if (!strcmp(kind, \"scalar\")) {")
        appendLine("            if (fscanf(m, \"%llu\", &value) != 1) broken(\"bad scalar\");")
        for (p in sig.scalars) {
            appendLine("            if (!strcmp(name, \"${p.name}\")) { memcpy(&${p.name}_v, &value, sizeof ${p.name}_v); ${p.name}_set = 1; continue; }")
        }
        appendLine("        } else if (!strcmp(kind, \"array\")) {")
        appendLine("            if (fscanf(m, \"%llu %4095s %4095s\", &elements, in, out) != 3) broken(\"bad array\");")
        for (p in sig.arrays) {
            appendLine("            if (!strcmp(name, \"${p.name}\")) { ${p.name}_a = load(elements, ${p.type.bytes}, in, out); ${p.name}_set = 1; continue; }")
        }
        appendLine("        }")
        appendLine("        broken(\"unknown manifest entry\");")
        appendLine("    }")
        appendLine("    fclose(m);")
        appendLine("    if (${sig.params.joinToString(" || ") { "!${it.name}_set" }}) broken(\"incomplete manifest\");")
        val args = sig.params.joinToString(", ") { p ->
            if (p.role == ParamRole.SCALAR) "${p.name}_v" else "(${CSignature.paramDecl(p).substringBeforeLast(p.name).trim()})${p.name}_a.data"
        }
        appendLine("    ${sig.function}($args);")
        for (p in sig.outputs) appendLine("    save(&${p.name}_a);")
        appendLine("    return 0;")
        appendLine("}")
    }

    @Language("C")
    private val PRELUDE = """
        // Generated by the judge (RiscvHarness), version $VERSION.
        #include <stdint.h>
        #include <stdio.h>
        #include <stdlib.h>
        #include <string.h>

        #define PATH_LEN 4096

        typedef struct {
            void* data;
            size_t bytes;
            char out[PATH_LEN];
        } Array;

        static void broken(const char* what) {
            fprintf(stderr, "harness: %s\n", what);
            exit($EXIT_BROKEN);
        }

        static Array load(unsigned long long elements, size_t size, const char* in, const char* out) {
            Array a;
            a.bytes = (size_t)elements * size;
            a.data = aligned_alloc(64, (a.bytes + 63) / 64 * 64 + 64);
            if (!a.data) broken("out of memory");
            memset(a.data, 0xFF, a.bytes);
            snprintf(a.out, PATH_LEN, "%s", strcmp(out, "-") ? out : "");
            if (strcmp(in, "-")) {
                FILE* f = fopen(in, "rb");
                if (!f || fread(a.data, 1, a.bytes, f) != a.bytes) broken("cannot read an input");
                fclose(f);
            }
            return a;
        }

        static void save(const Array* a) {
            FILE* f = fopen(a->out, "wb");
            if (!f || fwrite(a->data, 1, a->bytes, f) != a->bytes || fclose(f)) broken("cannot write an output");
        }


    """.trimIndent() + "\n"
}
